#!/usr/bin/env python3
"""Compile-only safety gates: enabling PWM cannot omit measured pulse limits."""
import os
from pathlib import Path
import subprocess

include = Path(__file__).resolve().parents[1] / "include"
base = [os.environ.get("CXX", "c++"), "-std=c++11", "-x", "c++", "-fsyntax-only", "-", "-I", str(include), "-DFEEL_BOARD_CLASSIC"]


def check(flags, success):
    result = subprocess.run(base + flags, input='#include "board_config.hpp"\n', capture_output=True, text=True, timeout=15)
    assert (result.returncode == 0) == success, result.stderr


check([], True)
check(["-DFEEL_ENABLE_SERVO_OUTPUT=1"], False)
check(["-DFEEL_ENABLE_SERVO_OUTPUT=1", "-DFEEL_VERIFIED_PULSE_MIN_US=900"], False)
check(["-DFEEL_ENABLE_SERVO_OUTPUT=1", "-DFEEL_VERIFIED_PULSE_MIN_US=900", "-DFEEL_VERIFIED_PULSE_MAX_US=2100"], True)
check(["-DFEEL_ENABLE_SERVO_OUTPUT=1", "-DFEEL_VERIFIED_PULSE_MIN_US=2100", "-DFEEL_VERIFIED_PULSE_MAX_US=900"], False)
check(["-DFEEL_ENABLE_SERVO_OUTPUT=1", "-DFEEL_VERIFIED_PULSE_MIN_US=500", "-DFEEL_VERIFIED_PULSE_MAX_US=2500"], False)
check(["-DFEEL_ENABLE_SERVO_OUTPUT=1", "-DFEEL_VERIFIED_PULSE_MIN_US=650", "-DFEEL_VERIFIED_PULSE_MAX_US=2500"], False)
check(["-DFEEL_ENABLE_SERVO_OUTPUT=1", "-DFEEL_VERIFIED_PULSE_MIN_US=899", "-DFEEL_VERIFIED_PULSE_MAX_US=2100"], False)
check(["-DFEEL_ENABLE_SERVO_OUTPUT=1", "-DFEEL_VERIFIED_PULSE_MIN_US=900", "-DFEEL_VERIFIED_PULSE_MAX_US=2101"], False)
check(["-DFEEL_ENABLE_SERVO_OUTPUT=1", "-DFEEL_VERIFIED_PULSE_MIN_US=1000", "-DFEEL_VERIFIED_PULSE_MAX_US=2000"], True)
check(["-DFEEL_SINGLE_SERVO_DEMO=1"], True)
check(["-DFEEL_SINGLE_SERVO_DEMO=1", "-DFEEL_ENABLE_SERVO_OUTPUT=1", "-DFEEL_VERIFIED_PULSE_MIN_US=900", "-DFEEL_VERIFIED_PULSE_MAX_US=2100"], False)
check(["-DFEEL_SINGLE_SERVO_DEMO=1", "-UFEEL_BOARD_CLASSIC"], False)
check(["-DFEEL_SINGLE_SERVO_DEMO=1", "-DFEEL_BOARD_S3"], False)
check(["-DFEEL_SINGLE_SERVO_LIVE=1"], True)
check(["-DFEEL_SINGLE_SERVO_LIVE=1", "-DFEEL_SINGLE_SERVO_DEMO=1"], False)
check(["-DFEEL_SINGLE_SERVO_LIVE=1", "-DFEEL_ENABLE_SERVO_OUTPUT=1", "-DFEEL_VERIFIED_PULSE_MIN_US=900", "-DFEEL_VERIFIED_PULSE_MAX_US=2100"], False)
check(["-DFEEL_SINGLE_SERVO_LIVE=1", "-UFEEL_BOARD_CLASSIC"], False)
check(["-DFEEL_SINGLE_SERVO_LIVE=1", "-DFEEL_BOARD_S3"], False)
check(["-DFEEL_SINGLE_SERVO_LIVE=1", "-DCONFIG_IDF_TARGET_ESP32S3"], False)
check(["-DFEEL_SINGLE_SERVO_DEMO=1", "-DCONFIG_IDF_TARGET_ESP32S3"], False)
check(["-DFEEL_PRODUCTION_PROFILE=1"], False)
check(["-DFEEL_PRODUCTION_PROFILE=1", "-DFEEL_ENABLE_SERVO_OUTPUT=1", "-DFEEL_VERIFIED_PULSE_MIN_US=900", "-DFEEL_VERIFIED_PULSE_MAX_US=2100"], False)
check(["-DFEEL_PRODUCTION_PROFILE=1", "-DFEEL_PRODUCTION_MEASUREMENTS_LOADED=1", "-DFEEL_ENABLE_SERVO_OUTPUT=1", "-DFEEL_VERIFIED_PULSE_MIN_US=900", "-DFEEL_VERIFIED_PULSE_MAX_US=2100"], True)
check(["-DFEEL_PRODUCTION_PROFILE=1", "-DFEEL_PRODUCTION_MEASUREMENTS_LOADED=1", "-DFEEL_ENABLE_SERVO_OUTPUT=1", "-DFEEL_VERIFIED_PULSE_MIN_US=900", "-DFEEL_VERIFIED_PULSE_MAX_US=2100", "-DFEEL_SINGLE_SERVO_LIVE=1"], False)
print("PASS firmware board config: 25 compile-only default/range/single/production isolation checks (no physical outputs)")
